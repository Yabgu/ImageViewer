#!/usr/bin/env bash
#
# Compile the exported .iwi and plugin headers as C11, and fail if they have
# regressed to C++-only declarations.
#
# Why this exists
# ---------------
# ImagePluginDef.h and IwiFile.h are C headers.  Tension binds the format
# through FFI and a C game engine would consume it the same way, so a C
# compiler accepting them is the actual contract - not a nicety.  When five
# `enum X : uint8_t` declarations appeared in ImagePluginDef.h the whole project
# still built, because the project is C++ and nothing was compiling the header
# as C.  Those declarations are C23; the consumers are C11.
#
# Standalone on purpose
# --------------------
# This script does not configure or build the project.  An earlier version did
# (`cmake --build --target iwi_c_header_gate`), which meant the gate inherited
# every dependency the project has - doctest for the test tree, libpng for the
# converter, a compiler environment for MSVC - and a gate that fails because
# libpng is missing teaches people to ignore it.  Here the only inputs are a C
# compiler and two include directories.
#
# The assertions themselves live in src/tests/abi/iwi_c_gate_body.h, which is
# also what the CMake target compiles, so the two routes check the same text.
# The translation unit is generated in a temporary directory: the repository
# keeps a "no .c source files" rule and this gate is not an exception to it.
#
# Usage:
#   ci/check-iwi-c-header.sh
#
# Environment:
#   CC   compiler to use (default: clang, then cc, then gcc)

set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

if [ -n "${CC:-}" ]; then
    compiler=${CC}
elif command -v clang >/dev/null 2>&1; then
    compiler=clang
elif command -v cc >/dev/null 2>&1; then
    compiler=cc
elif command -v gcc >/dev/null 2>&1; then
    compiler=gcc
else
    echo "check-iwi-c-header: no C compiler found (set CC=...)" >&2
    exit 2
fi

# An explicit CC that does not resolve should say so, not be reported as a
# header regression: the two failures need different fixes and the second one
# blames the wrong file.
if ! command -v "${compiler}" >/dev/null 2>&1; then
    echo "check-iwi-c-header: '${compiler}' is not runnable (set CC=...)" >&2
    exit 2
fi

work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT

cat > "${work}/gate.c" <<'EOF'
/* Generated by ci/check-iwi-c-header.sh - do not edit.
 *
 * A translation unit whose only job is to be compiled as C11.  The assertions
 * are in iwi_c_gate_body.h, the same file the CMake target compiles.
 */
#include "iwi_c_gate_body.h"

int main(void) { return 0; }
EOF

echo "check-iwi-c-header: ${compiler} -x c -std=c11 -pedantic-errors"
echo "check-iwi-c-header: format dir  ${root}/src/format"
echo "check-iwi-c-header: plugin dir  ${root}/src/imageviewer"
echo "check-iwi-c-header: gate body  ${root}/src/tests/abi"

# -pedantic-errors turns "this is a C23 extension" into a hard error, which is
# the entire point: the consumers are C11, not C23.
if ! "${compiler}" -x c -std=c11 -pedantic-errors -Wall -Wextra -Werror \
        -I "${root}/src/format" \
        -I "${root}/src/imageviewer" \
        -I "${root}/src/tests/abi" \
        -fsyntax-only "${work}/gate.c"; then
    cat >&2 <<'MSG'

The exported headers no longer compile as C11.

Most likely causes:
  - an `enum Name : type` declaration (C23, not C11) outside an
    `#ifdef __cplusplus` guard
  - a signature mentioning a C++ type (std::, a class, a template)
  - a construct only legal in C++ used in a position C also parses

The header is a C contract.  Guard the C++ form, or use the typedef plus
#define form the C path already uses.
MSG
    exit 1
fi

echo "check-iwi-c-header: OK - the exported headers compile as C11"
