#!/usr/bin/env python3
"""
gen_bluenoise.py — generate the 64x64 blue-noise threshold tile used by
FilterCore's BlueNoise / SpatialTemporal modes.

Method: Ulichney's void-and-cluster algorithm (R. A. Ulichney, "The void-and-
cluster method for generating digital halftone screens", 1993) on a torus.

  1. Start from a sparse random binary pattern (10% occupied).
  2. Refine it: move the tightest cluster into the largest void until the two
     coincide.
  3. Phase 1: repeatedly remove the tightest cluster and record its rank,
     producing the low half of the ordering (ranks 0 .. M-1).
  4. Phase 2: starting from the refined pattern, repeatedly insert into the
     largest void and record its rank (ranks M .. N*N-1).

The result is a permutation of 0 .. N*N-1.  A pixel's threshold is
(rank + 0.5) / (N*N), i.e. never 0 and never 1, so a constant input produces a
spatially uniform average over the tile.

The kernel is Gaussian with sigma = 1.5 and radius 6, evaluated on the torus.

Usage:
    python gen_bluenoise.py > ../imageviewer/BlueNoiseTile.hpp
"""

import math
import random
import sys

N = 64
SIGMA = 1.5
RADIUS = 6
SEED = 20261029          # fixed: the checked-in tile must be reproducible
OCCUPANCY = 0.10

TOTAL = N * N


def make_kernel():
    """Gaussian weights over the (2*RADIUS+1)^2 neighbourhood."""
    k = []
    for dy in range(-RADIUS, RADIUS + 1):
        for dx in range(-RADIUS, RADIUS + 1):
            if dx * dx + dy * dy > RADIUS * RADIUS:
                continue
            k.append((dx, dy, math.exp(-(dx * dx + dy * dy) / (2.0 * SIGMA * SIGMA))))
    return k


KERNEL = make_kernel()


def neighbours():
    """For every cell, the list of (cell_index, weight) it influences."""
    table = []
    for y in range(N):
        for x in range(N):
            cells = []
            for dx, dy, w in KERNEL:
                cells.append(((y + dy) % N * N + (x + dx) % N, w))
            table.append(cells)
    return table


NEIGHBOURS = neighbours()


def energy_from(grid):
    e = [0.0] * TOTAL
    for i, occupied in enumerate(grid):
        if occupied:
            for j, w in NEIGHBOURS[i]:
                e[j] += w
    return e


def add(grid, energy, i, sign):
    grid[i] += sign
    for j, w in NEIGHBOURS[i]:
        energy[j] += sign * w


def tightest_cluster(grid, energy):
    best, best_e = -1, -1.0
    for i in range(TOTAL):
        if grid[i] and energy[i] > best_e:
            best, best_e = i, energy[i]
    return best


def largest_void(grid, energy):
    best, best_e = -1, float("inf")
    for i in range(TOTAL):
        if not grid[i] and energy[i] < best_e:
            best, best_e = i, energy[i]
    return best


def main():
    rng = random.Random(SEED)

    grid = [0] * TOTAL
    initial = int(TOTAL * OCCUPANCY)
    for i in rng.sample(range(TOTAL), initial):
        grid[i] = 1
    energy = energy_from(grid)

    # Refine: move the tightest cluster into the largest void until it stays put.
    for _ in range(10 * TOTAL):
        c = tightest_cluster(grid, energy)
        add(grid, energy, c, -1)
        v = largest_void(grid, energy)
        add(grid, energy, v, +1)
        if v == c:
            break

    ranks = [-1] * TOTAL

    # Phase 1: remove tightest clusters, ranking from M-1 down to 0.
    rank = initial - 1
    while rank >= 0:
        c = tightest_cluster(grid, energy)
        if c < 0:
            break
        add(grid, energy, c, -1)
        ranks[c] = rank
        rank -= 1

    # Phase 2: from the refined pattern again, fill the largest voids upward.
    grid = [0] * TOTAL
    for i in range(TOTAL):
        if ranks[i] >= 0:
            grid[i] = 1
    energy = energy_from(grid)
    rank = initial
    while rank < TOTAL:
        v = largest_void(grid, energy)
        if v < 0:
            break
        add(grid, energy, v, +1)
        ranks[v] = rank
        rank += 1

    assert sorted(ranks) == list(range(TOTAL)), "tile is not a permutation"

    out = sys.stdout
    out.write("// Generated by src/tools/gen_bluenoise.py — do not edit by hand.\n")
    out.write("// 64x64 void-and-cluster (Ulichney 1993), torus, Gaussian sigma=1.5,\n")
    out.write("// radius 6, seed %d.  Values are ranks 0..4095; the threshold for a\n" % SEED)
    out.write("// pixel is (rank + 0.5) / 4096.\n")
    out.write("#pragma once\n#include <cstdint>\n\n")
    out.write("static const uint16_t kBlueNoise64[64][64] = {\n")
    for y in range(N):
        row = ", ".join("%4d" % ranks[y * N + x] for x in range(N))
        out.write("    { %s },\n" % row)
    out.write("};\n")


if __name__ == "__main__":
    main()
